"""JIANT 0.9.20: MONK's being, the six faces (assets/ui-art/monk/{rest,ah,oo,ee,mm,chant}.png) as run-length frames.

  gen_monk.py IN_DIR OUT.h [--png PREVIEW.png]

Each picture is scaled to MK_W x MK_W px (a box filter: the art's ~56 cells, 2 px a cell) and its colours taken to a
palette of 13 shared by all six (k-means over the frames' opaque pixels). Around each figure its outline ring, the
pixels within 2 px of it (14) and within 4 px (15), which ui_engvis.c vx_monk draws in red as the being pulses. A frame
is one run-length stream over its rows (a run may carry on to the next row): a byte (n - 1) << 4 | i, n 1..16 px of
colour i (0 nothing, 1..13 MK_PAL, 14 15 the ring). rest is whole; the other five only where they differ from it, as
pairs of a skip (the pixels rest's, a 255 carrying on into the next byte) and a run. Out: MK_PAL (RGB565), MK_RLE,
MK_OFF[7] (each frame's start: rest ah oo ee mm chant, then the end). Needs numpy and PIL (run by hand: the header is
committed, firmware/src/ui_monk.h).
"""
import sys
import numpy as np
from PIL import Image

W = 112
NAMES = ['rest', 'ah', 'oo', 'ee', 'mm', 'chant']
K = 13
RING = (2, 4)


def kmeans(px, k, seed=7):
    rng = np.random.default_rng(seed)
    c = px[rng.choice(len(px), k, replace=False)].astype(float)
    for _ in range(40):
        lab = ((px[:, None] - c[None]) ** 2).sum(-1).argmin(1)
        c = np.array([px[lab == j].mean(0) if (lab == j).any() else c[j] for j in range(k)])
    return c[np.argsort(c.sum(1))]


def dilate(m, d):
    p = np.pad(m, d)
    o = np.zeros_like(m)
    for dy in range(-d, d + 1):
        for dx in range(-d, d + 1):
            o |= p[d + dy:d + dy + m.shape[0], d + dx:d + dx + m.shape[1]]
    return o


def rle(idx):
    out, flat, i = [], idx.ravel(), 0
    while i < len(flat):
        j = i
        while j < len(flat) and j - i < 16 and flat[j] == flat[i]:
            j += 1
        out.append((j - i - 1) << 4 | int(flat[i]))
        i = j
    return out


def diff(base, idx):
    """a face over rest: (skip, run) pairs: skip the pixels rest keeps (255s carry on), then a run as rle's"""
    out, a, b, i, last = [], base.ravel(), idx.ravel(), 0, 0
    while i < len(b):
        if a[i] == b[i]:
            i += 1
            continue
        j = i
        while j < len(b) and j - i < 16 and b[j] == b[i] and a[j] != b[j]:
            j += 1
        k = i - last
        while k >= 255:
            out.append(255)
            k -= 255
        out += [k, (j - i - 1) << 4 | int(b[i])]
        i = last = j
    return out


def main():
    src, dst = sys.argv[1], sys.argv[2]
    png = sys.argv[sys.argv.index('--png') + 1] if '--png' in sys.argv else None
    fr = [np.array(Image.open(f'{src}/{n}.png').convert('RGBA').resize((W, W), Image.BOX)).astype(float) for n in NAMES]
    ops = [f[..., 3] >= 128 for f in fr]
    pal = kmeans(np.concatenate([f[..., :3][o] for f, o in zip(fr, ops)]), K)
    rgb = [tuple(int(round(v)) for v in c) for c in pal]
    idxs, data, off = [], [], []
    for k, (f, o) in enumerate(zip(fr, ops)):
        lab = ((f[..., None, :3] - pal[None, None]) ** 2).sum(-1).argmin(-1) + 1
        idx = np.where(o, lab, 0)
        idx = np.where(~o & dilate(o, RING[0]), 14, idx)
        idx = np.where((idx == 0) & dilate(o, RING[1]), 15, idx)
        idxs.append(idx)
        off.append(len(data))
        data += rle(idx) if k == 0 else diff(idxs[0], idx)
    off.append(len(data))
    with open(dst, 'w') as h:
        h.write('/* generated by tools/gen_monk.py from assets/ui-art/monk/*.png: MONK\'s being, six faces */\n#pragma once\n')
        h.write(f'#define MK_W {W}\n')
        h.write('static const uint16_t MK_PAL[%d] = {0, %s};\n' % (K + 1, ', '.join(
            '0x%04Xu' % ((r >> 3) << 11 | (g >> 2) << 5 | b >> 3) for r, g, b in rgb)))
        h.write('static const uint16_t MK_OFF[%d] = {%s};\n' % (len(off), ', '.join(map(str, off))))
        h.write('static const uint8_t MK_RLE[%d] = {\n' % len(data))
        for i in range(0, len(data), 24):
            h.write('    ' + ', '.join(str(v) for v in data[i:i + 24]) + ',\n')
        h.write('};\n')
    if png:
        s = 3
        im = Image.new('RGB', (len(NAMES) * W * s, W * s), (243, 234, 216))
        cols = [None] + rgb + [(220, 23, 9), (240, 150, 130)]
        for k, idx in enumerate(idxs):
            for y in range(W):
                for x in range(W):
                    if idx[y, x]:
                        im.paste(cols[idx[y, x]], (k * W * s + x * s, y * s, k * W * s + x * s + s, y * s + s))
        im.save(png)
    print(f'{dst}: {len(data)} B of runs, {2 * len(off)} B of offsets, palette {K}')


if __name__ == '__main__':
    main()
