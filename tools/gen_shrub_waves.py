"""SHRUB's wavetable: 8 single-cycle frames of 256 samples, Q15, smooth to harsh.

Writes firmware/src/shrub_tables.c with  const int16_t SHRUB_WT[8][256].
Frames: 0 sine, 1 soft triangle, 2 saw-ish (24 harmonics), 3 square-ish, 4 PWM-ish (duty 1/4),
5 formant-like (two bands of harmonics), 6 hard saw (64 harmonics), 7 noisy-bright (64 harmonics,
fixed random phases and levels from a fixed LCG). Each frame is normalised to the same peak.
Deterministic: fixed constants only, pure python3 stdlib, no PIL, no random module.
Usage: tools/gen_shrub_waves.py [OUT.c]   (default firmware/src/shrub_tables.c)
"""
import math
import sys
from pathlib import Path

N = 256              # samples per cycle
FRAMES = 8
PEAK = 30000         # Q15 peak of every frame (headroom for the filter and the voice level)


def lcg_stream(seed):
    s = seed
    while True:
        s = (s * 1103515245 + 12345) & 0x7FFFFFFF
        yield s / 0x7FFFFFFF


def additive(terms):
    """terms: (harmonic, amplitude, phase in radians)"""
    out = [0.0] * N
    for n, a, ph in terms:
        w = 2.0 * math.pi * n / N
        for k in range(N):
            out[k] += a * math.sin(w * k + ph)
    return out


def frame_terms(f):
    if f == 0:      # sine
        return [(1, 1.0, 0.0)]
    if f == 1:      # soft triangle: odd harmonics, 1/n^2, alternating
        return [(n, (-1.0) ** ((n - 1) // 2) / (n * n), math.pi / 2) for n in range(1, 16, 2)]
    if f == 2:      # saw-ish: 24 harmonics, 1/n
        return [(n, (-1.0) ** (n + 1) / n, 0.0) for n in range(1, 25)]
    if f == 3:      # square-ish: odd harmonics, 1/n
        return [(n, 1.0 / n, 0.0) for n in range(1, 24, 2)]
    if f == 4:      # PWM-ish: a pulse of duty 1/4 (cosine series)
        d = 0.25
        return [(n, 2.0 * math.sin(n * math.pi * d) / (n * math.pi), math.pi / 2) for n in range(1, 33)]
    if f == 5:      # formant-like: bands around harmonics 3 and 9
        t = []
        for n in range(1, 33):
            g = math.exp(-((n - 3.0) ** 2) / 2.0) + 0.7 * math.exp(-((n - 9.0) ** 2) / 4.5)
            t.append((n, g / n ** 0.25, 0.0))
        return t
    if f == 6:      # hard saw: 64 harmonics
        return [(n, (-1.0) ** (n + 1) / n, 0.0) for n in range(1, 65)]
    # noisy-bright: 64 harmonics, levels and phases from a fixed stream
    rnd = lcg_stream(0x5EED)
    t = []
    for n in range(1, 65):
        lvl = (0.6 + 0.8 * next(rnd)) / math.sqrt(n)
        t.append((n, lvl, 2.0 * math.pi * next(rnd)))
    return t


def frame(f):
    s = additive(frame_terms(f))
    peak = max(abs(v) for v in s)
    return [int(math.floor(v * PEAK / peak + 0.5)) for v in s]


def emit(frames):
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 Leo Kuroshita (@kurogedelic), Hügelton Instruments */",
        "/* GENERATED by tools/gen_shrub_waves.py: SHRUB's wavetable (8 frames x 256, Q15, smooth to harsh).",
        " * Do not edit; run the generator. */",
        "#ifndef SHRUB_TABLES_C",
        "#define SHRUB_TABLES_C",
        "const int16_t SHRUB_WT[8][256] = {",
    ]
    for f, s in enumerate(frames):
        lines.append("    { /* frame %d */" % f)
        for k in range(0, N, 16):
            lines.append("        " + ",".join("%d" % v for v in s[k:k + 16]) + ",")
        lines.append("    },")
    lines.append("};")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    root = Path(__file__).resolve().parent.parent
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "firmware" / "src" / "shrub_tables.c"
    frames = [frame(f) for f in range(FRAMES)]
    out.write_text(emit(frames), encoding="utf-8")
    print("wrote %s (%d frames x %d samples)" % (out, FRAMES, N))


if __name__ == "__main__":
    main()
