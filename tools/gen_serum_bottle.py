# SERUM's bottle (firmware/src/serum_bottle.h): a 40 x 40 pixel atomiser, drawn cell by cell from the owner's
# reference, mirrored left to right so the body sits on the left and the bulb on the right.
#   python3 tools/gen_serum_bottle.py [OUT.h]
import math
import sys
from pathlib import Path

N = 40

def rnd(v):
    # JavaScript's Math.round: halves go up
    return math.floor(v + 0.5)

def paint(x, y):
    """the colour of the cell at (x, y) before mirroring, or None: the bulb, the tube, the body, the neck, the cap"""
    col = None
    dx, dy = (x - 8) / 6, (y - 22) / 4.5
    if dx * dx + dy * dy <= 1:                                   # rubber bulb, left
        col = "#e07aa8"
        if (x * 3 + y * 5) % 11 == 0:
            col = "#f9e3ee"
        if (x - 6) ** 2 / 4 + (y - 19) ** 2 / 2 <= 1:
            col = "#f6c3d9"
    if 12 <= x <= 19:                                            # tube from the bulb to the head
        ty = rnd(22 - (x - 12) * 0.8)
        if y == ty or y == ty + 1:
            col = "#b8a06a"
    dx, dy = (x - 27) / 11, (y - 28) / 10
    if dx * dx + dy * dy <= 1:                                   # bottle body
        col = "#f29b6b"
        if (x - 27) ** 2 / 64 + (y - 28) ** 2 / 49 <= 1:
            col = "#f8b48c"
        if (x - 23) ** 2 / 16 + (y - 25) ** 2 / 9 <= 1:
            col = "#fde3d2"
    if 22 <= x <= 32 and 15 <= y <= 19:                          # neck
        col = "#b5801f" if y == 17 else "#e9b13a"
    if 24 <= x <= 30 and 9 <= y <= 14:                           # cap
        col = "#fff1b8" if x == 25 else "#f3c75a"
    if 26 <= x <= 28 and 5 <= y <= 8:                            # pump
        col = "#e9b13a"
    return col

def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "firmware" / "src" / "serum_bottle.h"
    pal = []
    cells = []
    for y in range(N):
        for c in range(N):
            col = paint(N - 1 - c, y)                            # mirrored: displayed column c is original column 39 - c
            if col is None:
                cells.append(0)
                continue
            if col not in pal:
                pal.append(col)
            cells.append(pal.index(col) + 1)
    if len(pal) > 15:
        raise SystemExit("too many colours for a nibble")
    rgb = []
    for hx in pal:
        r, g, b = int(hx[1:3], 16), int(hx[3:5], 16), int(hx[5:7], 16)
        rgb.append("0x%04Xu" % (((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)))
    packed = [cells[i] | (cells[i + 1] << 4) for i in range(0, len(cells), 2)]
    lines = [
        "/* GENERATED by tools/gen_serum_bottle.py: SERUM's bottle, %d x %d cells, mirrored left to right (the body on the" % (N, N),
        " * left). A cell is a nibble, the palette index (0 = clear), two cells a byte, the even cell in the low nibble. */",
        "#define SB_N %d" % N,
        "static const uint16_t SB_PAL[%d] = {0, %s};" % (len(rgb) + 1, ", ".join(rgb)),
        "static const uint8_t SB_CELLS[%d] = {" % len(packed),
    ]
    for i in range(0, len(packed), 16):
        lines.append("    " + ", ".join("0x%02X" % v for v in packed[i:i + 16]) + ",")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print("serum bottle: %d colours, %d bytes -> %s" % (len(pal), len(packed), out))

if __name__ == "__main__":
    main()
